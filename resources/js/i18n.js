export const translations = { ar, he, en };

export function localField(obj, field, locale) {
    if (!obj) return '';
    if (locale === 'ar') return obj[field] ?? '';
    const val = obj[`${field}_${locale}`];
    return (val && val.trim()) ? val : (obj[field] ?? '');
}
